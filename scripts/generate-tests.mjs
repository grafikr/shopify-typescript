#!/usr/bin/env node
// Generates tests/fixtures.test-d.ts from everything in fixtures/.
//
// Every fixture is a real response captured from a Shopify store. For each one
// the generated test asserts that
//   1. the response is assignable to its type (missing fields, wrong types,
//      missing nullability), and
//   2. the response has no keys the type does not declare.
//
// Usage: node scripts/generate-tests.mjs         (or `pnpm generate`)
//        node scripts/generate-tests.mjs --list  print which type each fixture is checked against
import { readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

/** [fixture path regex, type expression, optional accessor]. First match wins. */
const RULES = [
  [/^js\/cart-add-error/, 'Js.CartError'],
  [/^js\/cart-change-error/, 'Js.CartError'],
  [/^js\/cart-update-error/, 'Js.CartError'],
  [/^js\/cart-add-single/, 'Js.CartAddSingleResponse'],
  [/^js\/cart-add-/, 'Js.CartAddResponse'],
  [/^js\/cart-update-/, 'Js.CartUpdateResponse'],
  [/^js\/cart-change-/, 'Js.CartChangeResponse'],
  [/^js\/cart-shipping-rates/, 'Js.ShippingRatesResponse'],
  [/^js\/variant/, 'Js.ProductVariant'],
  [/^json\/variant/, "Endpoints['/variants/:id.json']"],
  [/^json\/products/, "Endpoints['/products.json']"],
  [
    /^json\/collection-products/,
    "Endpoints['/collections/:handle/products.json']",
  ],
  [/^json\/collections/, "Endpoints['/collections.json']"],
  [/^json\/collection-/, "Endpoints['/collections/:handle.json']"],
  [/^json\/pages/, "Endpoints['/pages.json']"],
  [/^json\/page-/, "Endpoints['/pages/:handle.json']"],
  [/^json\/policy/, "Endpoints['/policies/:handle.json']"],
  [/^json\/search-suggest/, "Endpoints['/search/suggest.json']"],
  [/^json\/meta/, "Endpoints['/meta.json']"],
  [/^json\/product-oembed/, "Endpoints['/products/:handle.oembed']"],
  [
    /^json\/browsing-context/,
    "Endpoints['/browsing_context_suggestions.json']",
  ],
  [/^json\/recommendations/, "Endpoints['/recommendations/products.json']"],
  [/^liquid\/collection-products-/, 'Array<Liquid.Product>'],
  [/^liquid\/collection-/, 'Liquid.Collection'],
  [/^liquid\/article-/, 'Liquid.Article'],
  [/^liquid\/pagination-/, 'Liquid.Pagination'],
  [
    /^global\/shopify/,
    "Omit<Shopify, 'analytics' | 'loadFeatures' | 'autoloadFeatures'>",
  ],
  [/^js\/cart-clear/, 'Js.CartClearResponse'],
  [/^js\/cart/, 'Js.Cart'],
  [/^json\/cart/, 'Json.Cart'],
  [/^liquid\/cart/, 'Liquid.Cart'],
  [/^js\/product/, 'Js.Product'],
  [/^json\/product/, 'Json.Product', '.product'],
  [/^liquid\/product/, 'Liquid.Product'],
];

const dirs = readdirSync('fixtures', { withFileTypes: true }).filter((d) =>
  d.isDirectory(),
);
const files = dirs
  .flatMap((d) =>
    readdirSync(join('fixtures', d.name)).map((f) => `${d.name}/${f}`),
  )
  .filter((f) => f.endsWith('.json'))
  .sort();

const list = process.argv.includes('--list');
const imports = [];
const body = [];
const unmatched = [];
for (const rel of files) {
  const rule = RULES.find(([re]) => re.test(rel));
  if (!rule) {
    unmatched.push(rel);
    continue;
  }
  const [, type, accessor = ''] = rule;
  if (list) console.log(`${rel.padEnd(78)} ${type}${accessor}`);
  const name = rel.slice(0, -5).replace(/[^A-Za-z0-9]/g, '_');
  imports.push(`import ${name} from '../fixtures/${rel}';`);
  body.push(`export const ${name}_check: Widen<${type}> = ${name}${accessor};`);
  body.push(
    `export const ${name}_extra: NoExtra<typeof ${name}${accessor}, ${type}> = true;`,
  );
}

if (unmatched.length > 0) {
  console.error(`No rule for fixtures:\n  ${unmatched.join('\n  ')}`);
  process.exit(1);
}

const output = `// Generated by scripts/generate-tests.mjs. Do not edit by hand.
import type { Shopify } from '../global/Shopify';
import type { Endpoints, Js, Json, Liquid } from '../src';
${imports.join('\n')}

/**
 * JSON imports widen string literals to \`string\`, so we compare against a
 * widened version of our types. Structure, optionality and nullability are
 * still checked. Enum-like values are asserted in enums.test-d.ts.
 */
type Widen<T> = T extends string
  ? string
  : T extends ReadonlyArray<infer U>
    ? Array<Widen<U>>
    : T extends object
      ? { [K in keyof T]: Widen<T[K]> }
      : T;

type KeysOf<T> = T extends unknown ? keyof T : never;
type ElemOf<T> = T extends ReadonlyArray<infer U> ? U : never;
type PropOf<T, K> = T extends unknown ? (K extends keyof T ? T[K] : never) : never;

/** Union of the key paths present in the fixture \`F\` but not declared on the type \`T\`. */
type Extra<F, T> = unknown extends T
  ? never
  : F extends ReadonlyArray<infer FU>
    ? Extra<FU, ElemOf<T>>
    : F extends object
      ? { [K in keyof F & string]: K extends KeysOf<T> ? Extra<F[K], PropOf<T, K>> : K }[keyof F & string]
      : never;

/** \`true\` when the fixture has no keys the type does not declare, otherwise the offending keys. */
type NoExtra<F, T> = [Extra<F, T>] extends [never] ? true : Extra<F, T>;

${body.join('\n')}
`;

if (!list) writeFileSync('tests/fixtures.test-d.ts', output);
if (!list) console.log(`Generated tests for ${files.length} fixtures`);
